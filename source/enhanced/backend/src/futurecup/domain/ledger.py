"""Durability contracts. Integer resource units are NOT supplier currency/billing."""
from dataclasses import dataclass
from typing import Protocol
from futurecup.domain.errors import RuntimeFault
from futurecup.domain.models import VersionRef


@dataclass(frozen=True, slots=True)
class CallContext:
    account_id: str
    reservation_id: str
    run_id: str
    node_id: str
    execution_id: str
    kind: str
    input_hash: str
    units: int


@dataclass(frozen=True, slots=True)
class ReconciliationFinding:
    code: str
    record_id: str
    action: str = "manual_review"


class ToolReplayMetadata(Protocol):
    ref: VersionRef
    retry_safety: str


class RecoveryLedger(Protocol):
    worker_id: str
    def digest(self, value: object) -> str: ...
    def create_account(self, account_id: str, owner_id: str, *, max_calls: int, max_units: int, unit: str = "resource_units") -> dict: ...
    def reservation(self, identifier: str) -> dict: ...
    def uncertain(self, identifier: str) -> None: ...
    def tool(self, identifier: str) -> dict: ...
    def claim_unknown_tool(self, tool_id: str, request_id: str, *, allow_idempotent: bool = False) -> bool: ...
    def recover(self, dead_worker: str, *, confirmed_stopped: bool = False) -> dict: ...
    def reconcile(self, observations: tuple[dict, ...] = (), *, complete_inventory: bool = False) -> tuple[ReconciliationFinding, ...]: ...
    def account(self, account_id: str) -> dict: ...
    def reserve(self, context: CallContext) -> dict: ...
    def dispatch(self, reservation_id: str) -> None: ...
    def commit(self, reservation_id: str, units: int, evidence_id: str) -> None: ...
    def release(self, reservation_id: str) -> None: ...
    def start_tool(self, context: CallContext, *, tool_call_id: str, tool_name: str,
                   tool_version: str, side_effect_class: str, replay_scope: str) -> dict: ...
    def succeed_tool(self, tool_id: str, reservation_id: str, result: object) -> None: ...
    def fail_tool(self, tool_id: str, reservation_id: str) -> None: ...
    def tool_result(self, tool_id: str) -> object: ...
    def reusable_tool(self, account_id: str, scope: str, tool_name: str, version: str) -> bool: ...


def refused(code: str) -> RuntimeFault:
    return RuntimeFault(code, "Durability journal requires consistent evidence or explicit reconciliation", 409)
