class RuntimeToolGateway(Protocol):
    """Trusted in-process tools now; an MCP gateway can implement this later.

    Not a sandbox and not an implementation of the future isolated ToolExecutor.
    """
    async def replay_definition(self, allowed: tuple[VersionRef, ...], name: str) -> ToolReplayMetadata: ...
    def retry_safe(self, allowed: tuple[VersionRef,...]) -> bool: ...
    def resume_safe(self, allowed: tuple[VersionRef,...], scope: str) -> bool: ...
    async def invoke_replay(self, allowed: tuple[VersionRef,...], name: str, arguments: dict, scope: str) -> JsonValue: ...
    async def definitions(self, allowed: tuple[VersionRef, ...]) -> tuple[dict[str, JsonValue], ...]: ...
    async def invoke(self, allowed: tuple[VersionRef, ...], name: str,
                     arguments: dict[str, JsonValue]) -> JsonValue: ...


